def _call_llm_api(prompt: str, context_str: str = "") -> str:
    """Вызов открытой LLM через OpenAI-совместимый эндпоинт (Groq / vLLM / Ollama)."""
    api_key = os.environ.get("LLM_API_KEY") or os.environ.get("GROQ_API_KEY") or os.environ.get("OPENAI_API_KEY")
    if not api_key:
        return ""
        
    base_url = os.environ.get("LLM_BASE_URL", "https://api.groq.com/openai/v1").rstrip("/")
    model = os.environ.get("LLM_MODEL", "llama-3.3-70b-versatile")
    
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
    ]
    if context_str:
        messages.append({"role": "system", "content": f"Контекст текущей заявки клиента:\n{context_str}"})
    messages.append({"role": "user", "content": prompt})
    
    payload = json.dumps({
        "model": model,
        "messages": messages,
        "temperature": 0.3,
        "max_tokens": 300
    }).encode("utf-8")
    
    url = f"{base_url}/chat/completions"
    req = urllib.request.Request(
        url,
        data=payload,
        headers={
            "Content-Type": "application/json",
            "Authorization": f"Bearer {api_key}"
        }
    )
    
    try:
        with urllib.request.urlopen(req, timeout=7) as response:
            res_data = json.loads(response.read().decode("utf-8"))
            return res_data["choices"][0]["message"]["content"].strip()
    except Exception as e:
        # При любых сбоях сети/лимитах бесшовно переходим к локальному экспертному движку
        return ""

def ask_assistant(question: str, context: dict | None = None) -> dict:
    """
    Основная функция запроса к ассистенту.
    Возвращает dict с ответом и источником (LLM_ONLINE или RULE_BASED_OFFLINE).
    """
    clean_q = question.strip().lower()
    context_str = ""
    if context:
        context_str = (
            f"- ИНН: {context.get('inn', 'N/A')}\n"
            f"- Выручка: {context.get('annual_revenue', 0):,} ₽\n"
            f"- Запрос: {context.get('requested_amount', 0):,} ₽ на {context.get('requested_term_months', 0)} мес\n"
            f"- Статус: {context.get('status', 'N/A')}\n"
            f"- Зона риска: {context.get('risk_zone', 'N/A')}"
        )
        
    # 1. Пробуем получить ответ через настроенный OpenAI-совместимый LLM API
    llm_answer = _call_llm_api(question, context_str)
    if llm_answer:
        return {
            "answer": llm_answer,
            "source": "LLM_OPEN_WEIGHTS",
            "model": os.environ.get("LLM_MODEL", "llama-3.3-70b-versatile")
        }
        
    # 2. Интеллектуальный поиск по экспертным намерениям (Offline Fallback)
    for intent in FALLBACK_INTENTS:
        if any(kw in clean_q for kw in intent["keywords"]):
            return {
                "answer": intent["answer"],
                "source": "SMART_EXPERT_SYSTEM",
                "model": "Alfa-Rules-Fallback"
            }
            
    # Базовый универсальный ответ ассистента
    default_text = (
        "Я могу подробно рассказать об условиях кредитования Альфа-Банка, объяснить расчет "
        "одобренного лимита или помочь с подготовкой документов для рассмотрения заявки. "
        "Спросите меня, например: «Почему банк снизил сумму?», «Что выбрать: овердрафт или оборотный кредит?» "
        "или «Как повысить одобренный лимит?»."
    )
    return {
        "answer": default_text,
        "source": "SMART_EXPERT_SYSTEM",
        "model": "Alfa-Rules-Fallback"
    }

